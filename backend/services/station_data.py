class StationData:
    """서울지하철 역 정보를 관리하는 클래스
    
    ✨ 개선사항: 성능 최적화를 위한 역 이름 → ID 매핑 인덱스 추가
    """
    
    def __init__(self):
        # 로깅 설정
        self.logger = logging.getLogger(__name__)
        
        # 경량화: 불필요한 station_info 제거됨
        
        # 🚀 성능 최적화: 역 이름 → ID 매핑 인덱스 생성
        self._name_to_ids_index = self._build_name_to_ids_index()
        
        # 🚀 성능 최적화: 정규화된 역 이름 → ID 매핑 인덱스 생성
        self._normalized_name_to_ids_index = self._build_normalized_name_to_ids_index()
        
        self.logger.info(f"StationData 초기화 완료 - 총 {len(STATION_ID_TO_NAME)}개 역 정보 로드")
    
    def _build_name_to_ids_index(self) -> Dict[str, List[str]]:
        """역 이름 → ID 매핑 인덱스를 생성합니다."""
        index = {}
        for station_id, name in STATION_ID_TO_NAME.items():
            if name not in index:
                index[name] = []
            index[name].append(station_id)
        return index
    
    def _build_normalized_name_to_ids_index(self) -> Dict[str, List[str]]:
        """정규화된 역 이름(역 제거) → ID 매핑 인덱스를 생성합니다."""
        index = {}
        for station_id, name in STATION_ID_TO_NAME.items():
            normalized_name = name.replace('역', '')
            if normalized_name not in index:
                index[normalized_name] = []
            index[normalized_name].append(station_id)
        return index
    
    # 역 ID를 사용하여 해당 역의 이름을 반환
    def get_station_name_from_id(self, station_id: str) -> str:
        """역 ID에서 역 이름을 반환합니다."""
        return STATION_ID_TO_NAME.get(station_id, "")
    
    # 역 이름을 사용하여 해당하는 모든 역 ID 목록을 반환
    def search_station_id_by_name(self, station_name: str) -> List[str]:
        """역 이름으로 해당하는 모든 역 ID를 찾습니다.
        
        ✨ 개선사항: 
        - False Positive 방지를 위한 정확한 매칭 우선시
        - 인덱스 활용으로 성능 최적화
        """
        # 역 이름에서 '역' 제거 후 검색
        clean_name = station_name.replace('역', '')
        result = []
        
        # 1단계: 정확한 매칭 우선 (인덱스 활용)
        # 원본 이름으로 검색
        if station_name in self._name_to_ids_index:
            result.extend(self._name_to_ids_index[station_name])
        
        # 정규화된 이름으로 검색
        if clean_name in self._normalized_name_to_ids_index:
            result.extend(self._normalized_name_to_ids_index[clean_name])
        
        # 중복 제거
        result = list(set(result))
        
        # 2단계: 정확한 매칭이 없는 경우에만 부분 매칭 수행
        if not result:
            # 부분 매칭 시 더 엄격한 조건 적용
            for station_id, name in STATION_ID_TO_NAME.items():
                clean_station_name = name.replace('역', '')
                
                # 조건 1: 검색어가 역 이름에 포함되는 경우 (길이 제한)
                if (clean_name in clean_station_name and 
                    len(clean_name) >= 2 and  # 최소 2글자 이상
                    len(clean_name) / len(clean_station_name) >= 0.5):  # 검색어가 역 이름의 50% 이상
                    result.append(station_id)
                
                # 조건 2: 역 이름이 검색어에 포함되는 경우 (정확한 매칭에 가까운 경우)
                elif (clean_station_name in clean_name and 
                      len(clean_station_name) >= 2 and
                      len(clean_station_name) / len(clean_name) >= 0.7):  # 역 이름이 검색어의 70% 이상
                    result.append(station_id)
        
        return result
    
    # 전체 지하철 역 이름 목록을 반환
    def get_all_station_names(self) -> List[str]:
        """모든 역 이름 목록을 반환합니다."""
        return list(STATION_ID_TO_NAME.values())
    
    # 특정 노선의 모든 역 정보를 반환
    def get_station_by_line(self, line_code: str) -> List[Dict]:
        """특정 노선의 모든 역을 반환합니다."""
        result = []
        for station_id, name in STATION_ID_TO_NAME.items():
            if station_id.startswith(line_code):
                result.append({
                    "station_id": station_id,
                    "station_name": name,
                    "line_code": line_code
                })
        
        return result

    # 역 이름으로 환승 여부, 노선 정보 등 상세 정보를 반환
    def get_station_info(self, station_name: str) -> Dict:
        """역 이름으로 상세 정보를 반환합니다.
        
        ✨ 개선사항: 결과 포맷 보장 및 None 처리 개선
        """
        # 입력 검증
        if not station_name or not isinstance(station_name, str):
            self.logger.warning(f"잘못된 역 이름 입력: {station_name}")
            return {
                "name": "",
                "is_transfer": False,
                "lines": [],
                "line_count": 0,
                "error": "잘못된 역 이름입니다."
            }
        
        # 역 이름 정규화
        normalized_station = station_name.strip()
        
        # 해당 역의 모든 ID 찾기 (정확한 매칭 우선)
        station_ids = []
        
        # 1. 정확한 매칭 시도
        for station_id, name in STATION_ID_TO_NAME.items():
            if normalized_station == name:
                station_ids.append(station_id)
        
        # 2. 정확한 매칭이 없으면 부분 매칭 시도
        if not station_ids:
            for station_id, name in STATION_ID_TO_NAME.items():
                # "역" 제거 후 비교
                clean_name = name.replace('역', '')
                clean_station = normalized_station.replace('역', '')
                
                # 정확한 매칭 또는 포함 관계 확인
                if (clean_station == clean_name or 
                    clean_station in clean_name or 
                    clean_name in clean_station):
                    station_ids.append(station_id)
        
        # 기본 응답 구조 보장
        base_result = {
            "name": normalized_station,
            "is_transfer": False,
            "lines": [],
            "line_count": 0
        }
        
        if not station_ids:
            self.logger.info(f"역 정보를 찾을 수 없음: {station_name}")
            base_result["error"] = "해당 역을 찾을 수 없습니다."
            return base_result
        
        # 노선 정보 추출
        lines = []
        for station_id in station_ids:
            line_code = station_id[:4]  # 처음 4자리가 노선 코드
            line_name = self._get_line_name(line_code)
            if line_name:
                lines.append({
                    "line_code": line_code,
                    "line_name": line_name,
                    "station_id": station_id
                })
        
        # 결과 구성 (항상 일정한 포맷 보장)
        result = {
            "name": normalized_station,
            "is_transfer": len(lines) > 1,  # 2개 이상 노선이면 환승역
            "lines": lines,
            "line_count": len(lines)
        }
        
        self.logger.debug(f"역 정보 조회 완료: {normalized_station} - {len(lines)}개 노선")
        return result

